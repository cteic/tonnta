// Rebuilds src/bathing-waters.generated.ts from the EPA's bathing-water list.
// Run from packages/data: node scripts/generate-bathing-waters.mjs
// Only stable fields are written. Ratings, lifeguards and restrictions are
// fetched live, so the registry only needs a rerun when the EPA adds or
// removes an Identified Bathing Water.
import { writeFileSync } from 'node:fs';

import { bathingWaterSlug } from '../src/bathing-water-slug.ts';
import { irishGridToWgs84 } from '../src/irish-grid.ts';

const SOURCE = 'https://data.epa.ie/bw/api/v1/locations?per_page=500';
const OUTPUT = new URL('../src/bathing-waters.generated.ts', import.meta.url);

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`EPA locations: HTTP ${response.status}`);
const payload = await response.json();
if (!Array.isArray(payload.list)) throw new Error('EPA locations: unexpected response shape');

const identified = payload.list.filter((row) => row.beach_type === 'Identified Beach');
const counts = new Map();
for (const row of identified) {
  const slug = bathingWaterSlug(row.beach_name);
  counts.set(slug, (counts.get(slug) ?? 0) + 1);
}

const round = (value) => Math.round(value * 1e5) / 1e5;
const waters = identified
  .map((row) => {
    if (typeof row.easting !== 'number' || typeof row.northing !== 'number') {
      throw new Error(`EPA locations: ${row.beach_id} has no grid position`);
    }
    const base = bathingWaterSlug(row.beach_name);
    const slug = counts.get(base) > 1 ? `${base}-${bathingWaterSlug(row.county_name)}` : base;
    const { latitude, longitude } = irishGridToWgs84(row.easting, row.northing);
    return {
      id: row.beach_id,
      slug,
      name: row.beach_name.trim(),
      county: row.county_name,
      localAuthority: row.local_authority_name,
      latitude: round(latitude),
      longitude: round(longitude),
    };
  })
  .sort((a, b) => a.slug.localeCompare(b.slug));

if (new Set(waters.map((water) => water.slug)).size !== waters.length) {
  throw new Error('EPA locations: duplicate slugs after county suffix');
}

const generatedOn = new Date().toISOString().slice(0, 10);
writeFileSync(
  OUTPUT,
  `// Generated by scripts/generate-bathing-waters.mjs on ${generatedOn}. Do not edit.
// Source: EPA bathing water locations (data.epa.ie), CC BY 4.0. Identified Bathing Waters only.
import type { BathingWater } from '@tonnta/types';

export const BATHING_WATERS: readonly BathingWater[] = ${JSON.stringify(waters, null, 2)};
`
);
console.log(`Wrote ${waters.length} bathing waters`);
